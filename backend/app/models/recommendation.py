import uuid
from datetime import UTC, datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Integer, Text, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base

if TYPE_CHECKING:
    from app.models.catalog import CatalogProduct
    from app.models.screening_session import ScreeningSession
    from app.models.user import User


class EyewearRecommendation(Base):
    """
    Persisted eyewear recommendations generated by the deterministic scoring engine.
    Stores input preferences, ranked product matches, and match explanation rationales.
    """

    __tablename__ = "eyewear_recommendations"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    session_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("screening_sessions.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    input_criteria: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )  # JSON-serialized preferences: budget, frame_shape, frame_material, style, etc.
    recommendations_json: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )  # JSON-serialized ranked matches: product_id, score, reasons, pricing
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )

    # Relationships
    user: Mapped["User"] = relationship(
        "User",
        foreign_keys=[user_id],
    )
    session: Mapped["ScreeningSession | None"] = relationship(
        "ScreeningSession",
        foreign_keys=[session_id],
    )
    feedbacks: Mapped[list["RecommendationFeedback"]] = relationship(
        "RecommendationFeedback",
        back_populates="recommendation",
        cascade="all, delete-orphan",
    )


class RecommendationFeedback(Base):
    """Subject/patient feedback and rating on generated eyewear recommendations."""

    __tablename__ = "recommendation_feedbacks"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    recommendation_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("eyewear_recommendations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    selected_product_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("catalog_products.id", ondelete="SET NULL"),
        nullable=True,
    )
    rating: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )  # 1 to 5 star rating
    feedback_text: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )

    # Relationships
    recommendation: Mapped["EyewearRecommendation"] = relationship(
        "EyewearRecommendation",
        back_populates="feedbacks",
    )
    user: Mapped["User"] = relationship(
        "User",
        foreign_keys=[user_id],
    )
    selected_product: Mapped["CatalogProduct | None"] = relationship(
        "CatalogProduct",
        foreign_keys=[selected_product_id],
    )
